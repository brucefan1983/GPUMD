"""DFT-D3 zero damping, D3(0) (`dftd3 <functional> <rc> <rc_cn> [zero|bj]`). Contract tested:

1. Reference: energy, forces and virial against stored simple-dftd3 1.7.0 values (zero damping,
   two-body only, same cutoffs; fixtures/dftd3_zero/reference.json, provenance in
   fixtures/dftd3_zero/generate_reference.py and README.md): PBE on seven structures plus a
   heavy-element cell, revPBE/BLYP/B3LYP/TPSS on three. The D3 contribution is isolated as
   (run with `dftd3`) - (same run without), NEP89 underneath. All 48 functionals of the zero-damping
   table are checked on one small H/C/O cell (fixtures/dftd3_zero/all_functionals.json, generated by
   generate_all_functionals.py) with an all-zero NEP.
2. Parser and error behaviour (token handling, unknown functional for zero, Z >= 87 with zero).
3. BJ unchanged: `dftd3 pbe 12 6` and the explicit `... bj` reproduce the frozen output of the unmodified
   upstream binary 84fd855e (fixtures/dftd3_zero/bj_frozen.json): bitwise where that binary is deterministic
   (tiny24, benzene_dimer), within 3x its own run-to-run spread (bj_spread.json) elsewhere. These use an
   all-zero NEP (output = D3 alone); NEP89 itself is not reproducible run to run.
4. Force and virial consistency with finite differences of the energy.
5. Robustness: small-box and large-box path agreement, and no NaN/inf for r << R0.

Tests marked "BJ compat" must pass on the unmodified binary as well, except those that use the explicit
`bj` token; all others need the zero damping feature.

Tolerances (reference tests): min(cap, max(2 x BASELINE, floor)). Caps: relative 2e-6 of the D3 energy and
of the largest virial component, 1e-5 eV/A for forces. Floors: 2e-6 eV, 1e-6 eV/A, 2e-5 eV (virial).
BASELINE values are the median errors measured for this implementation itself (`ZERO_BASELINE`,
fixtures/dftd3_zero/zero_baseline.json): the tests detect changes of the implementation and bound the error
by the caps. A tolerance is not to be loosened to make a test pass.
"""
